class PythonLoggingStrategy(LoggingStrategy):
    """Standard Python logging strategy."""

    def generate(self, config: LoggingConfig) -> str:
        """Generate Python logging configuration."""
        if config.format == LogFormat.JSON:
            return self._generate_json(config)
        return self._generate_text(config)

    def _generate_text(self, config: LoggingConfig) -> str:
        return f'''"""
Python Logging Configuration
Generated by AI Orchestrator
"""

import logging
import sys
import os
from logging.handlers import RotatingFileHandler, TimedRotatingFileHandler
from datetime import datetime

# ═══════════════════════════════════════════════════════════════
# Configuration
# ═══════════════════════════════════════════════════════════════

LOG_LEVEL = logging.{config.level.value.upper()}
LOG_FORMAT = "%(asctime)s | %(levelname)-8s | %(name)s:%(funcName)s:%(lineno)d - %(message)s"
LOG_DATE_FORMAT = "%Y-%m-%d %H:%M:%S"

# ═══════════════════════════════════════════════════════════════
# Logger Setup
# ═══════════════════════════════════════════════════════════════

def setup_logger(name: str = "app") -> logging.Logger:
    """Set up logger with console and file handlers."""
    logger = logging.getLogger(name)
    logger.setLevel(LOG_LEVEL)

    # Create formatter
    formatter = logging.Formatter(LOG_FORMAT, datefmt=LOG_DATE_FORMAT)

    # Console handler
    console_handler = logging.StreamHandler(sys.stdout)
    console_handler.setLevel(LOG_LEVEL)
    console_handler.setFormatter(formatter)
    logger.addHandler(console_handler)

    # File handler with rotation
    log_dir = os.path.join(os.path.dirname(__file__), "logs")
    os.makedirs(log_dir, exist_ok=True)

    file_handler = RotatingFileHandler(
        os.path.join(log_dir, f"{{name}}.log"),
        maxBytes=10*1024*1024,  # 10 MB
        backupCount=5,
    )
    file_handler.setLevel(LOG_LEVEL)
    file_handler.setFormatter(formatter)
    logger.addHandler(file_handler)

    return logger

# ═══════════════════════════════════════════════════════════════
# Helper Functions
# ═══════════════════════════════════════════════════════════════

def get_logger(name: str = "app") -> logging.Logger:
    """Get logger instance."""
    return setup_logger(name)

def log_with_context(
    logger: logging.Logger,
    level: str,
    message: str,
    **context,
):
    """Log with additional context."""
    extra = {{k: v for k, v in context.items()}}
    logger.log(getattr(logging, level.upper()), message, extra=extra)

# ═══════════════════════════════════════════════════════════════
# Export
# ═══════════════════════════════════════════════════════════════

__all__ = ["setup_logger", "get_logger", "log_with_context"]
'''

