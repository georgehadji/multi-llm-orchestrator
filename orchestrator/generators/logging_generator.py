class LoggingConfigBuilder:
    """
    Builder for logging configuration.

    Fluent interface for constructing logging configs.
    """

    def __init__(self):
        """Initialize builder."""
        self._language: str = "typescript"
        self._framework: str = "winston"
        self._level: LogLevel = LogLevel.INFO
        self._format: LogFormat = LogFormat.JSON
        self._transports: List[Dict[str, Any]] = []
        self._rotation: Optional[Dict[str, Any]] = None
        self._correlation_id: bool = False

    def for_node(self) -> "LoggingConfigBuilder":
        """Configure for Node.js."""
        self._language = "typescript"
        return self

    def for_python(self) -> "LoggingConfigBuilder":
        """Configure for Python."""
        self._language = "python"
        return self

    def with_winston(self) -> "LoggingConfigBuilder":
        """Use Winston framework."""
        self._framework = "winston"
        return self

    def with_pino(self) -> "LoggingConfigBuilder":
        """Use Pino framework."""
        self._framework = "pino"
        return self

    def with_loguru(self) -> "LoggingConfigBuilder":
        """Use Loguru framework."""
        self._framework = "loguru"
        return self

    def with_standard_logging(self) -> "LoggingConfigBuilder":
        """Use standard Python logging."""
        self._framework = "logging"
        return self

    def with_level(self, level: LogLevel) -> "LoggingConfigBuilder":
        """Set log level."""
        self._level = level
        return self

    def with_format(self, format: LogFormat) -> "LoggingConfigBuilder":
        """Set log format."""
        self._format = format
        return self

    def add_console_transport(self) -> "LoggingConfigBuilder":
        """Add console transport."""
        self._transports.append({"type": "console"})
        return self

    def add_file_transport(
        self,
        filename: str = "app.log",
        rotation: str = "daily",
    ) -> "LoggingConfigBuilder":
        """Add file transport."""
        self._transports.append(
            {
                "type": "file",
                "filename": filename,
                "rotation": rotation,
            }
        )
        return self

    def with_correlation_id(self) -> "LoggingConfigBuilder":
        """Thread a per-request correlation id into every JSON log record."""
        self._correlation_id = True
        return self

    def add_rotation(
        self,
        max_size: str = "10MB",
        backup_count: int = 5,
    ) -> "LoggingConfigBuilder":
        """Add log rotation."""
        self._rotation = {
            "max_size": max_size,
            "backup_count": backup_count,
        }
        return self

    def build(self) -> str:
        """Build logging configuration."""
        config = LoggingConfig(
            language=self._language,
            framework=self._framework,
            level=self._level,
            format=self._format,
            transports=self._transports,
            rotation=self._rotation,
            correlation_id=self._correlation_id,
        )

        strategy = self._get_strategy()
        return strategy.generate(config)

    def _get_strategy(self) -> LoggingStrategy:
        """
        Get logging strategy.

        Returns:
            LoggingStrategy for configured framework

        Note: Falls back to Winston with warning for unknown frameworks.
        This is intentional for backwards compatibility, but logs a warning
        so users are aware of the misconfiguration.
        """
        strategies = {
            "winston": WinstonLoggingStrategy(),
            "pino": PinoLoggingStrategy(),
            "loguru": LoguruLoggingStrategy(),
            "logging": PythonLoggingStrategy(),
        }

        # Handle None or missing framework
        if self._framework is None:
            import logging

            logger = logging.getLogger(__name__)
            logger.warning(
                "Logging framework is None. Falling back to Winston. "
                f"Supported frameworks: {list(strategies.keys())}"
            )
            return WinstonLoggingStrategy()

        # Get strategy with validation
        strategy = strategies.get(self._framework)

        if strategy is None:
            import logging

            logger = logging.getLogger(__name__)
            logger.warning(
                f"Unknown logging framework '{self._framework}'. "
                f"Falling back to Winston. Supported frameworks: {list(strategies.keys())}"
            )
            return WinstonLoggingStrategy()

        return strategy


