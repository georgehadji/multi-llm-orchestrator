class CICDPipelineBuilder:
    """
    Builder Pattern for CI/CD pipelines.

    Fluent interface for constructing CI/CD configurations.

    Usage:
        pipeline = (CICDPipelineBuilder()
            .for_github_actions()
            .add_job("build", ["node"])
            .add_job("test", ["node"])
            .build())
    """

    def __init__(self):
        """Initialize builder."""
        self._name: str = "CI/CD Pipeline"
        self._provider: CICDProvider = CICDProvider.GITHUB_ACTIONS
        self._branches: List[str] = ["main", "develop"]
        self._jobs: List[JobConfig] = []
        self._env_vars: Dict[str, str] = {}
        self._secrets: List[str] = []
        self._strategy: CICDStrategy = GitHubActionsStrategy()

    def for_github_actions(self) -> "CICDPipelineBuilder":
        """Configure for GitHub Actions."""
        self._provider = CICDProvider.GITHUB_ACTIONS
        self._strategy = GitHubActionsStrategy()
        return self

    def for_gitlab_ci(self) -> "CICDPipelineBuilder":
        """Configure for GitLab CI."""
        self._provider = CICDProvider.GITLAB_CI
        self._strategy = GitLabCIStrategy()
        return self

    def for_azure_devops(self) -> "CICDPipelineBuilder":
        """Configure for Azure DevOps."""
        self._provider = CICDProvider.AZURE_DEVOPS
        self._strategy = AzureDevOpsStrategy()
        return self

    def with_name(self, name: str) -> "CICDPipelineBuilder":
        """Set pipeline name."""
        self._name = name
        return self

    def with_branches(self, branches: List[str]) -> "CICDPipelineBuilder":
        """Set target branches."""
        self._branches = branches
        return self

    def add_env_var(self, key: str, value: str) -> "CICDPipelineBuilder":
        """Add environment variable."""
        self._env_vars[key] = value
        return self

    def add_secret(self, secret: str) -> "CICDPipelineBuilder":
        """Add required secret."""
        self._secrets.append(secret)
        return self

    def add_job(
        self,
        name: str,
        languages: List[str] = None,
        job_type: str = "build",
        runs_on: str = "ubuntu-latest",
        needs: List[str] = None,
        timeout: int = 60,
    ) -> "CICDPipelineBuilder":
        """
        Add job to pipeline.

        Args:
            name: Job name
            languages: Programming languages
            job_type: Job type
            runs_on: Runner
            needs: Dependencies
            timeout: Timeout in minutes

        Returns:
            Self for fluent interface
        """
        steps = self._generate_steps(name, languages, job_type)

        job = JobConfig(
            name=name,
            job_type=JobType(job_type),
            runs_on=runs_on,
            steps=steps,
            needs=needs or [],
            timeout=timeout,
        )

        self._jobs.append(job)
        return self

    def _generate_steps(
        self,
        name: str,
        languages: List[str],
        job_type: str,
    ) -> List[Dict[str, Any]]:
        """Generate job steps based on language and type."""
        steps = []

        if job_type == "build":
            if "node" in languages:
                steps.extend(
                    [
                        {"name": "Setup Node.js", "run": "node --version"},
                        {"name": "Install dependencies", "run": "npm ci"},
                        {"name": "Build", "run": "npm run build"},
                    ]
                )
            if "python" in languages:
                steps.extend(
                    [
                        {"name": "Setup Python", "run": "python --version"},
                        {"name": "Install dependencies", "run": "pip install -r requirements.txt"},
                        {"name": "Build", "run": "python setup.py build"},
                    ]
                )

        elif job_type == "test":
            if "node" in languages:
                steps.extend(
                    [
                        {"name": "Setup Node.js", "run": "node --version"},
                        {"name": "Install dependencies", "run": "npm ci"},
                        {"name": "Run tests", "run": "npm test"},
                    ]
                )
            if "python" in languages:
                steps.extend(
                    [
                        {"name": "Setup Python", "run": "python --version"},
                        {"name": "Install dependencies", "run": "pip install -r requirements.txt"},
                        {"name": "Run tests", "run": "pytest"},
                    ]
                )

        elif job_type == "lint":
            if "node" in languages:
                steps.extend(
                    [
                        {"name": "Setup Node.js", "run": "node --version"},
                        {"name": "Install dependencies", "run": "npm ci"},
                        {"name": "Run linter", "run": "npm run lint"},
                    ]
                )

        elif job_type == "deploy":
            steps.extend(
                [
                    {"name": "Deploy", "run": "echo 'Deploying...'"},
                ]
            )

        return steps

    def build(self) -> str:
        """
        Build CI/CD configuration.

        Returns:
            Configuration file content
        """
        config = PipelineConfig(
            name=self._name,
            provider=self._provider,
            branches=self._branches,
            jobs=self._jobs,
            environment_variables=self._env_vars,
            secrets=self._secrets,
        )

        return self._strategy.generate(config)

    def build_to_file(self, filepath: str) -> str:
        """
        Build and write to file.

        Args:
            filepath: Output file path

        Returns:
            File path
        """
        content = self.build()

        with open(filepath, "w") as f:
            f.write(content)

        return filepath


