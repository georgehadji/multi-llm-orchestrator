def create_github_actions_pipeline(
    name: str = "CI/CD Pipeline",
    languages: List[str] = None,
) -> str:
    """
    Create GitHub Actions pipeline.

    Args:
        name: Pipeline name
        languages: Programming languages

    Returns:
        Workflow file content
    """
    builder = CICDPipelineBuilder().for_github_actions().with_name(name)

    if languages:
        builder.add_job("build", languages, "build")
        builder.add_job("test", languages, "test", needs=["build"])
        builder.add_job("lint", languages, "lint", needs=["build"])

    return builder.build()


