class ErrorHandlerGenerator:
    """
    Facade for error handler generation.

    Usage:
        generator = ErrorHandlerGenerator("typescript")
        handler = generator.generate()
    """

    def __init__(self, language: str = "typescript"):
        """Initialize generator."""
        self._strategies = {
            "typescript": TypeScriptErrorHandlerStrategy(),
            "python": PythonErrorHandlerStrategy(),
        }
        self._language = language

    def generate(self, config: ErrorConfig = None) -> ErrorHandler:
        """Generate error handler."""
        if config is None:
            config = ErrorConfig(language=self._language)

        strategy = self._strategies.get(self._language)

        if not strategy:
            raise ValueError(f"Unsupported language: {self._language}")

        return strategy.generate(config)

    def get_supported_languages(self) -> List[str]:
        """Get supported languages."""
        return list(self._strategies.keys())


