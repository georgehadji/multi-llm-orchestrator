class ErrorHandler:
    """Centralized error handler."""

    def __init__(
        self,
        log_errors: bool = True,
        include_stack_trace: bool = True,
        include_error_codes: bool = True,
        logger: Optional[logging.Logger] = None,
    ):
        self.log_errors = log_errors
        self.include_stack_trace = include_stack_trace
        self.include_error_codes = include_error_codes
        self.logger = logger or logging.getLogger(__name__)

    def handle(self, error: Exception) -> AppError:
        """Handle error."""
        if isinstance(error, AppError):
            self._log_error(error)
            return error

        # Wrap unknown errors
        app_error = InternalError(str(error))
        if self.include_stack_trace:
            app_error.with_metadata(stack_trace=traceback.format_exc())
        self._log_error(app_error)
        return app_error

    def handle_async(self, func: Callable):
        """Decorator for async error handling."""
        import functools
        import asyncio

        @functools.wraps(func)
        async def wrapper(*args, **kwargs):
            try:
                return await func(*args, **kwargs)
            except Exception as error:
                raise self.handle(error)

        return wrapper

    def _log_error(self, error: AppError) -> None:
        """Log error."""
        if not self.log_errors:
            return

        log_entry = {
            "level": error.level.value,
            "message": error.message,
            "code": error.code.value if self.include_error_codes else None,
            "metadata": error.metadata,
        }

        if self.include_stack_trace:
            log_entry["stack_trace"] = traceback.format_exc()

        log_func = {
            ErrorLevel.DEBUG: self.logger.debug,
            ErrorLevel.INFO: self.logger.info,
            ErrorLevel.WARNING: self.logger.warning,
            ErrorLevel.ERROR: self.logger.error,
            ErrorLevel.CRITICAL: self.logger.critical,
            ErrorLevel.FATAL: self.logger.critical,
        }.get(error.level, self.logger.error)

        log_func(log_entry)


