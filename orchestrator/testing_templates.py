class TestFramework(str, Enum):
    """Test framework enumeration."""

    JEST = "jest"
    VITEST = "vitest"
    PYTEST = "pytest"
    UNITTEST = "unittest"
    MOCHA = "mocha"
    JASMINE = "jasmine"


class TestType(str, Enum):
    """Test type enumeration."""

    UNIT = "unit"
    INTEGRATION = "integration"
    E2E = "e2e"
    COMPONENT = "component"
    SNAPSHOT = "snapshot"


@dataclass(frozen=True)
class TestConfig:
    """
    Immutable test configuration.

    Attributes:
        framework: Test framework
        test_type: Type of test
        coverage_threshold: Minimum coverage percentage
        timeout: Test timeout in ms
        retries: Number of retries
        parallel: Run tests in parallel
    """

    framework: TestFramework = TestFramework.JEST
    test_type: TestType = TestType.UNIT
    coverage_threshold: float = 80.0
    timeout: int = 5000
    retries: int = 0
    parallel: bool = True


@dataclass
class TestTemplate:
    """
    Test template prototype.

    Attributes:
        name: Test name
        framework: Test framework
        test_type: Test type
        template: Test template string
        imports: Required imports
        dependencies: Test dependencies
    """

    name: str
    framework: TestFramework
    test_type: TestType
    template: str
    imports: List[str] = field(default_factory=list)
    dependencies: List[str] = field(default_factory=list)

    def clone(self) -> "TestTemplate":
        """Clone template (Prototype pattern)."""
        return copy.deepcopy(self)

    def customize(self, **kwargs) -> "TestTemplate":
        """Customize cloned template."""
        cloned = self.clone()
        for key, value in kwargs.items():
            if hasattr(cloned, key):
                setattr(cloned, key, value)
        return cloned


