"""
Testing Templates Generator — Prototype + Factory Pattern
==========================================================
Author: Georgios-Chrysovalantis Chatzivantsidis

Testing template generation using Prototype Pattern for cloning test templates
and Factory Pattern for different test types.

Paradigm: OOP with Functional utilities
Patterns: Prototype, Factory Method, Builder, Template Method

Usage:
    from orchestrator.testing_templates import TestTemplateFactory

    factory = TestTemplateFactory()
    unit_test = factory.create_unit_test("MyComponent", framework="jest")
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import List, Dict
from enum import Enum
import copy

