class TestTemplateFactory:
    """
    Factory Method for test templates.

    Usage:
        factory = TestTemplateFactory()
        unit_test = factory.create_unit_test("MyComponent")
        component_test = factory.create_component_test("MyComponent")
    """

    def __init__(self):
        """Initialize factory with prototypes."""
        self._prototypes: Dict[str, TestTemplatePrototype] = {
            "jest_unit": JestUnitTestPrototype(),
            "vitest_unit": VitestUnitTestPrototype(),
            "pytest_unit": PytestUnitTestPrototype(),
            "react_component": ReactComponentTestPrototype(),
            "e2e": E2ETestPrototype(),
            "snapshot": SnapshotTestPrototype(),
        }

    def create_unit_test(
        self,
        name: str,
        framework: str = "jest",
        config: TestConfig = None,
    ) -> TestTemplate:
        """
        Create unit test template.

        Args:
            name: Component/function name
            framework: Test framework
            config: Test configuration

        Returns:
            TestTemplate
        """
        key = f"{framework}_unit"
        prototype = self._prototypes.get(key, self._prototypes["jest_unit"])

        if config is None:
            config = TestConfig(framework=TestFramework(framework))

        return prototype.create_template(name, config)

    def create_component_test(
        self,
        name: str,
        framework: str = "jest",
        config: TestConfig = None,
    ) -> TestTemplate:
        """
        Create component test template.

        Args:
            name: Component name
            framework: Test framework
            config: Test configuration

        Returns:
            TestTemplate
        """
        if framework == "jest":
            prototype = self._prototypes["react_component"]
        else:
            prototype = self._prototypes["jest_unit"]

        if config is None:
            config = TestConfig(test_type=TestType.COMPONENT)

        return prototype.create_template(name, config)

    def create_e2e_test(
        self,
        name: str,
        config: TestConfig = None,
    ) -> TestTemplate:
        """
        Create E2E test template.

        Args:
            name: Page/feature name
            config: Test configuration

        Returns:
            TestTemplate
        """
        prototype = self._prototypes["e2e"]

        if config is None:
            config = TestConfig(test_type=TestType.E2E)

        return prototype.create_template(name, config)

    def create_snapshot_test(
        self,
        name: str,
        config: TestConfig = None,
    ) -> TestTemplate:
        """
        Create snapshot test template.

        Args:
            name: Component name
            config: Test configuration

        Returns:
            TestTemplate
        """
        prototype = self._prototypes["snapshot"]

        if config is None:
            config = TestConfig(test_type=TestType.SNAPSHOT)

        return prototype.create_template(name, config)

    def create_custom_test(
        self,
        prototype_key: str,
        name: str,
        config: TestConfig = None,
    ) -> TestTemplate:
        """
        Create custom test from prototype key.

        Args:
            prototype_key: Prototype registry key
            name: Test name
            config: Test configuration

        Returns:
            TestTemplate
        """
        prototype = self._prototypes.get(prototype_key)

        if not prototype:
            raise ValueError(f"Unknown prototype: {prototype_key}")

        if config is None:
            config = TestConfig()

        return prototype.create_template(name, config)

    def register_prototype(
        self,
        key: str,
        prototype: TestTemplatePrototype,
    ) -> None:
        """
        Register custom prototype.

        Args:
            key: Prototype key
            prototype: Prototype instance
        """
        self._prototypes[key] = prototype


