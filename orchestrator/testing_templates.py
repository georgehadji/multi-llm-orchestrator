class TestTemplatePrototype(ABC):
    """
    Abstract base for test template prototypes.

    Subclasses implement specific test template types.
    """

    @abstractmethod
    def create_template(self, name: str, config: TestConfig) -> TestTemplate:
        """
        Create test template.

        Args:
            name: Test name
            config: Test configuration

        Returns:
            TestTemplate
        """
        pass


class JestUnitTestPrototype(TestTemplatePrototype):
    """
    Jest unit test template prototype.
    """

    def create_template(self, name: str, config: TestConfig) -> TestTemplate:
        """Create Jest unit test template."""
        template = f"""/**
 * Tests for {name}
 * @generated by AI Orchestrator
 */

import {{ describe, it, expect }} from '@jest/globals';

describe('{name}', () => {{
  describe('constructor', () => {{
    it('should create an instance', () => {{
      // TODO: Implement test
      expect(true).toBe(true);
    }});
  }});

  describe('basic functionality', () => {{
    it('should work as expected', () => {{
      // TODO: Implement test
      expect(true).toBe(true);
    }});
  }});
}});
"""

        return TestTemplate(
            name=name,
            framework=TestFramework.JEST,
            test_type=TestType.UNIT,
            template=template,
            imports=["@jest/globals"],
            dependencies=["jest", "@testing-library/jest-dom"],
        )


